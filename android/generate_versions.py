#!/usr/bin/env python3
"""Generate GameVersions.java (the launcher's executable hash table) from constants/game_versions.json."""
import json
from pathlib import Path

project = Path(__file__).resolve().parent.parent
data = json.loads((project / 'constants/game_versions.json').read_text())
out = project / 'android/app/src/main/java/org/fable2/recomp/GameVersions.java'


def q(s):
    return json.dumps(s)


rows = ',\n'.join(
    f'        new Version({q(v["hash"])}, {q(v["name"])}, {str(v["compatible"]).lower()}, {q(v["reason"])})'
    for v in data['versions'])
out.write_text(f'''package org.fable2.recomp;

// Generated by android/generate_versions.py from constants/game_versions.json; do not edit.
final class GameVersions {{
    static final class Version {{
        final String hash, name, message; final boolean supported;
        Version(String hash, String name, boolean supported, String message) {{
            this.hash = hash; this.name = name; this.supported = supported; this.message = message;
        }}
    }}
    static final Version[] ALL = {{
{rows}
    }};
    static Version find(String hash) {{
        for (Version v : ALL) if (v.hash.equalsIgnoreCase(hash)) return v;
        return null;
    }}
}}
''')
print(f'{out.name}: {len(data["versions"])} versions')
